pub struct FramebufferCanvas {
    fb: FramebufferInfo,
}

impl FramebufferCanvas {
    pub const fn new(fb: FramebufferInfo) -> Self {
        Self { fb }
    }

    #[inline(always)]
    pub fn put_pixel(&self, x: usize, y: usize, color: u32) {
        if x < self.fb.width && y < self.fb.height {
            let idx = y * self.fb.pixels_per_scanline + x;
            unsafe {
                (self.fb.base_address as *mut u32)
                    .add(idx)
                    .write_volatile(color);
            }
        }
    }

    pub fn fill_rect(&self, x0: usize, y0: usize, w: usize, h: usize, color: u32) {
        let x_end = (x0 + w).min(self.fb.width);
        let y_end = (y0 + h).min(self.fb.height);
        for y in y0..y_end {
            for x in x0..x_end {
                self.put_pixel(x, y, color);
            }
        }
    }

    /// Draw a single character scaled by `scale` (e.g. 2 = 16x16 pixels).
    pub fn draw_char(&self, x0: usize, y0: usize, ch: u8, color: u32, scale: usize) {
        let rows = glyph_8x8(ch);
        for (ry, row_bits) in rows.iter().copied().enumerate() {
            for rx in 0..8 {
                if (row_bits & (0x80 >> rx)) != 0 {
                    for sy in 0..scale {
                        for sx in 0..scale {
                            self.put_pixel(x0 + rx * scale + sx, y0 + ry * scale + sy, color);
                        }
                    }
                }
            }
        }
    }

    /// Draw an ASCII string at `(x0, y0)` with character scale `scale`.
    pub fn draw_str(&self, mut x: usize, y: usize, text: &str, color: u32, scale: usize) -> usize {
        let step = 8 * scale + scale; // 1-unit spacing between characters
        for b in text.bytes() {
            self.draw_char(x, y, b, color, scale);
            x += step;
        }
        x
    }

    /// Draw an unsigned 64-bit integer in decimal at `(x, y)`.
    pub fn draw_u64_dec(&self, x: usize, y: usize, mut val: u64, color: u32, scale: usize) -> usize {
        if val == 0 {
            return self.draw_str(x, y, "0", color, scale);
        }
        let mut buf = [0u8; 20];
        let mut i = 20;
        while val > 0 {
            i -= 1;
            buf[i] = b'0' + (val % 10) as u8;
            val /= 10;
        }
        let s = unsafe { core::str::from_utf8_unchecked(&buf[i..]) };
        self.draw_str(x, y, s, color, scale)
    }

    /// Draw an unsigned 64-bit integer as `0x` + 16 hex digits at `(x, y)`.
    pub fn draw_u64_hex(&self, x: usize, y: usize, val: u64, color: u32, scale: usize) -> usize {
        const HEX: &[u8; 16] = b"0123456789ABCDEF";
        let mut buf = [0u8; 18];
        buf[0] = b'0';
        buf[1] = b'X';
        for idx in 0..16 {
            let nibble = ((val >> ((15 - idx) * 4)) & 0xF) as usize;
            buf[2 + idx] = HEX[nibble];
        }
        let s = unsafe { core::str::from_utf8_unchecked(&buf) };
        self.draw_str(x, y, s, color, scale)
    }
}
