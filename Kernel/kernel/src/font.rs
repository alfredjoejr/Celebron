//! Built-in 8x8 bitmap font (ASCII 0x20..=0x7E) and 2x-scaled framebuffer text renderer
//! for Celebron OS Ring-0 early boot console.

use celebron_boot_info::{FramebufferInfo, PixelFormat};

/// Pack an RGB color (`r, g, b`) into the active framebuffer's 32-bit pixel format.
#[inline(always)]
pub fn pack_rgb(r: u8, g: u8, b: u8, format: PixelFormat) -> u32 {
    match format {
        PixelFormat::Bgr | PixelFormat::Bitmask => {
            ((r as u32) << 16) | ((g as u32) << 8) | (b as u32)
        }
        PixelFormat::Rgb => ((b as u32) << 16) | ((g as u32) << 8) | (r as u32),
    }
}

